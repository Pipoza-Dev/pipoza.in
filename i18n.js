/* ---------------- INITIALIZE & SWITCH LANGUAGE ---------------- */
PIPOZA.currentLang = localStorage.getItem('pipoza-lang') || 'en';

PIPOZA.t = function(key) {
  const dict = PIPOZA.TRANSLATIONS[PIPOZA.currentLang] || PIPOZA.TRANSLATIONS.en;
  return dict[key] || PIPOZA.TRANSLATIONS.en[key] || key;
};

PIPOZA.setLanguage = function(lang) {
  if (!PIPOZA.TRANSLATIONS[lang]) lang = 'en';
  PIPOZA.currentLang = lang;
  localStorage.setItem('pipoza-lang', lang);
  document.documentElement.setAttribute('lang', lang);

  // Update all [data-i18n] text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const trans = PIPOZA.t(key);
    if (trans) el.textContent = trans;
  });

  // Update all [data-i18n-html] elements (if contain formatting)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const trans = PIPOZA.t(key);
    if (trans) el.innerHTML = trans;
  });

  // Update all [data-i18n-placeholder] inputs
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const trans = PIPOZA.t(key);
    if (trans) el.placeholder = trans;
  });

  // Update active pill states in all language switchers
  document.querySelectorAll('.lang-pill').forEach(pill => {
    pill.classList.toggle('active', pill.dataset.lang === lang);
  });

  // Dispatch custom event for wizard or dynamic components
  window.dispatchEvent(new CustomEvent('pipoza:langchange', { detail: { lang } }));
};

/* ---------------- CREATE LANGUAGE SWITCHER WIDGET ---------------- */
PIPOZA.renderLangSwitcher = function() {
  const switchers = document.querySelectorAll('.lang-switcher');
  if (!switchers.length) return;

  const html = `
    <div class="lang-pills" role="group" aria-label="Language Selector">
      ${PIPOZA.LANGUAGES.map(l => `
        <button type="button" class="lang-pill ${PIPOZA.currentLang === l.code ? 'active' : ''}" data-lang="${l.code}" title="${l.name}">
          ${l.short}
        </button>
      `).join('')}
    </div>
  `;

  switchers.forEach(s => {
    s.innerHTML = html;
    s.querySelectorAll('.lang-pill').forEach(btn => {
      btn.addEventListener('click', () => {
        const target = btn.getAttribute('data-lang');
        PIPOZA.setLanguage(target);
        if (PIPOZA.audio && PIPOZA.audio.playPop) PIPOZA.audio.playPop(520, 0.03);
      });
    });
  });
};

